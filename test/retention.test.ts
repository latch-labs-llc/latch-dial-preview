import { INBOX_PREFIXES } from "../worker/src/inbox";

const WORKER = new URL("../worker/src/", import.meta.url).pathname;
const sources = readdirSync(WORKER).filter((f) => f.endsWith(".ts")).map((f) => readFileSync(WORKER + f, "utf8"));

/** Every env.KV.put(...) call with the literal prefix of its key. */
function puts(): { key: string; call: string }[] {
  const out: { key: string; call: string }[] = [];
  for (const src of sources) {
    for (const m of src.matchAll(/env\.KV\.put\(([\s\S]*?)\);/g)) {
      const first = m[1].trim();
      let key = first.startsWith("`") ? first.slice(1, first.indexOf("${")) : "";
      if (!key) {
        const id = first.split(",")[0].trim();
        const defs = [...src.matchAll(new RegExp(`const ${id} = \`([^$\`]*)`, "g"))];
        const distinct = new Set(defs.map((d) => d[1]));
        key = distinct.size === 1 ? defs[0][1] : `?${id} (unresolvable: use a literal key template)`;
      }
      out.push({ key, call: m[1] });
    }
  }
  return out;
}

describe("retention table vs the Worker", () => {
  const prefixes = RETENTION.filter((r) => r.store === "KV").map(literalPrefix);
  it("every KV write uses a listed prefix", () => {
    const ps = puts();
    expect(ps.length).toBeGreaterThan(8);
    for (const p of ps) expect(prefixes.some((x) => p.key === x || (p.key.startsWith(x) && x.length > 0)), `unlisted KV prefix ${p.key}`).toBe(true);
  });
  it("every KV write sets an expiry", () => {
    for (const p of puts()) expect(p.call, `no TTL on ${p.key}`).toMatch(/expirationTtl/);
  });
  it("Durable Object rows are exactly the Guards + Inbox prefixes, and KV never writes them", () => {
    const dos = [...GUARD_PREFIXES, ...INBOX_PREFIXES];
    expect(RETENTION.filter((r) => r.store === "Durable Object").map(literalPrefix).sort()).toEqual([...dos].sort());
    for (const p of puts()) for (const g of dos) expect(p.key.startsWith(g), `KV write to Durable Object prefix ${p.key}`).toBe(false);
  });
  it("every listed prefix is actually written (no stale rows)", () => {
    const keys = puts().map((p) => p.key);
    for (const x of prefixes) expect(keys.some((k) => k.startsWith(x)), `listed but never written: ${x}`).toBe(true);
  });
});

function tableMd(): string {
  return ["| Key prefix | Holds | Kept | Where | Deleted by |", "|---|---|---|---|---|", ...RETENTION.map((r) => `| \`${r.prefix}\` | ${r.holds} | ${r.ttl} | ${r.store} | ${r.deletedBy} |`)].join("\n");
}

describe("DATA-AND-RETENTION.md", () => {
  const path = new URL("../DATA-AND-RETENTION.md", import.meta.url).pathname;
  const sections: [string, string, string][] = [
    ["<!-- retention:begin (generated by test/retention.test.ts) -->", "<!-- retention:end -->", tableMd()],
    ["<!-- notkept:begin (generated by test/retention.test.ts) -->", "<!-- notkept:end -->", NOT_KEPT.map((x) => `- ${x}`).join("\n")],
    ["<!-- transit:begin (generated by test/retention.test.ts) -->", "<!-- transit:end -->", IN_TRANSIT.map((x) => `- ${x}`).join("\n")],
  ];
  it("lists every prefix exactly as the app does", () => {
    let md = readFileSync(path, "utf8");
    for (const [b, e, body] of sections) {
      const want = `${b}\n${body}\n${e}`;
      const i = md.indexOf(b);
      const j = md.indexOf(e) + e.length;
      expect(i).toBeGreaterThan(0);
      if (process.env.UPDATE_RETENTION) md = md.slice(0, i) + want + md.slice(j);
      else expect(md.slice(i, j)).toBe(want);
    }
    if (process.env.UPDATE_RETENTION) writeFileSync(path, md);
  });
});

describe("TTLs the Worker actually sets match the table", () => {
  it("handle, Telegram, used-login, writer, backup, lastIssued", async () => {
    const e = env();
    const kv = e.KV as MemKV;
    const w = wallet();
    await call(e, "POST", "/handles", { handle: "ttl_check", owner: w.pk, issued: NOW, sig: w.sign(handleClaimMessage("ttl_check", w.pk, NOW)) });
    const tg = tgAuth({ id: 3, username: "ttl_tg", auth_date: NOW });
    await call(e, "POST", "/telegram", { owner: w.pk, issued: NOW + 1, sig: w.sign(telegramLinkMessage(w.pk, 3, "ttl_tg", NOW + 1)), tg });
    const writer = wallet();
    await registerWriter(e, w, writer, NOW + 2);
    const deal = "cd".repeat(32);
    expect((await putBackup(e, w, writer, deal, wallet().pk, sized(9), NOW + 3)).status).toBe(200);
    const peer = wallet();
    await registerKeys(e, peer, msgKeys(peer), NOW);
    await registerKeys(e, w, msgKeys(w), NOW + 4);
    const sent = await postMsg(e, w, msgKeys(w), peer.pk, 0, msgSized(1), NOW + 5);
    expect(sent.status).toBe(200);
    const row = (p: string) => RETENTION.find((r) => r.prefix.startsWith(p))!.ttlSecs;
    const inboxRec = [...inboxStore(e, w.pk)!.m.entries()].find(([k]) => k.startsWith("msg:"))!;
    expect(inboxRec[1].exp - NOW).toBe(row("msg:"));
    const g = guardStore(e).m;
    expect(g.get(`tgu:${tg.hash}`).exp - NOW).toBe(row("tgu:"));
    expect(g.get(`li:${w.pk}`).exp - NOW).toBe(row("li:")); // call() runs every request at NOW
    for (const [key, p] of [
      ["h:ttl_check", "h:"],
      [`o:${w.pk}`, "o:"],
      ["tg:ttl_tg", "tg:"],
      [`tgo:${w.pk}`, "tgo:"],
      [`w:${w.pk}`, "w:"],
      [`b:${w.pk}:${deal}`, "b:"],
      [`mk:${w.pk}`, "mk:"],
      [`mc:${w.pk}:${String(Math.floor(NOW / 86400)).padStart(5, "0")}`, "mc:"],
    ] as const)
      expect(kv.ttl.get(key), key).toBe(row(p));
  });
});

describe("deletion", () => {
  async function setup() {
    const e = env();
    const w = wallet();
    const writer = wallet();
    await call(e, "POST", "/handles", { handle: "erase_me", owner: w.pk, issued: NOW, sig: w.sign(handleClaimMessage("erase_me", w.pk, NOW)) });
    const tg = tgAuth({ id: 8, username: "erase_tg", auth_date: NOW });
    await call(e, "POST", "/telegram", { owner: w.pk, issued: NOW + 1, sig: w.sign(telegramLinkMessage(w.pk, 8, "erase_tg", NOW + 1)), tg, findable: true });
    await registerWriter(e, w, writer, NOW + 2);
    for (const i of [0, 1]) expect((await putBackup(e, w, writer, String(i).repeat(64), wallet().pk, sized(i), NOW + 3 + i)).status).toBe(200);
    const peer = wallet();
    await registerKeys(e, peer, msgKeys(peer), NOW);
    expect((await registerKeys(e, w, msgKeys(w), NOW + 5)).status).toBe(200);
    expect((await postMsg(e, w, msgKeys(w), peer.pk, 0, msgSized(1), NOW + 6)).status).toBe(200);
    return { e, w, peer, kv: e.KV as MemKV };
  }

  it("DELETE /me (wallet-signed) removes handle, Telegram link, backups and writer, messaging keys and messages; li: stays briefly", async () => {
    const { e, w, peer, kv } = await setup();
    const other = wallet();
    expect((await call(e, "DELETE", "/me", { owner: w.pk, issued: NOW + 10, sig: other.sign(eraseMessage(w.pk, NOW + 10)) })).status).toBe(401);
    const r = await call(e, "DELETE", "/me", { owner: w.pk, issued: NOW + 10, sig: w.sign(eraseMessage(w.pk, NOW + 10)) });
    expect(r.status).toBe(200);
    expect(r.body.deleted).toBe(11); // h, o, tg, tgo, 2× b, w, mk, own inbox copy, the peer's copy of what w sent, mc
    const left = [...kv.m.keys()].filter((k) => k.includes(w.pk) || k.startsWith("h:erase_me") || k.startsWith("tg:erase_tg"));
    expect(left).toEqual([]);
    expect(inboxStore(e, w.pk)!.m.size).toBe(0);
    expect(inboxStore(e, peer.pk)!.m.size).toBe(0); // the peer's copy of the erased wallet's message went too
    expect(guardStore(e).m.has(`li:${w.pk}`)).toBe(true); // replay guard outlives deletion until it expires
    expect((await call(e, "GET", "/handles/erase_me")).status).toBe(404);
  });

  it("DELETE /backup: all, or one; wallet-signed; replay refused", async () => {
    const { e, w, kv } = await setup();
    const body = { issued: NOW + 10, sig: w.sign(backupDeleteMessage(w.pk, "all", NOW + 10)) };
    expect((await call(e, "DELETE", `/backup/${w.pk}`, body)).body.deleted).toBe(2);
    expect([...kv.m.keys()].filter((k) => k.startsWith(`b:${w.pk}`) || k === `w:${w.pk}`)).toEqual([]);
    expect((await call(e, "DELETE", `/backup/${w.pk}`, body)).status).toBe(409);
  });
});

