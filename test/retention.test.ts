import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { IN_TRANSIT, NOT_KEPT, RETENTION, literalPrefix } from "../src/lib/retention";
import { backupDeleteMessage, eraseMessage, handleClaimMessage, telegramLinkMessage } from "../src/lib/claims";
import { MemKV, NOW, call, env, guardStore, inboxStore, msgKeys, msgSized, postMsg, putBackup, registerKeys, registerWriter, sized, tgAuth, wallet } from "./svc";
