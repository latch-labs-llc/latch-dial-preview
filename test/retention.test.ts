describe("v0.5 #6: DELETE /me uses a per-owner hold index", () => {
  it("removes this wallet's holds without listing anyone else's", async () => {
    const e = env();
    const kv = e.KV as MemKV;
    const listed: string[] = [];
    const orig = kv.list.bind(kv);
    kv.list = async (o: any) => (listed.push(o.prefix), orig(o));
    const a = wallet();
    const b = wallet();
    await call(e, "POST", "/handles", { handle: "held_a1", owner: a.pk, issued: NOW, sig: a.sign(handleClaimMessage("held_a1", a.pk, NOW)) });
    await call(e, "POST", "/handles", { handle: "held_a2", owner: a.pk, issued: NOW + 1, sig: a.sign(handleClaimMessage("held_a2", a.pk, NOW + 1)) }); // holds held_a1
    await call(e, "POST", "/handles", { handle: "held_b1", owner: b.pk, issued: NOW, sig: b.sign(handleClaimMessage("held_b1", b.pk, NOW)) });
    await call(e, "POST", "/handles", { handle: "held_b2", owner: b.pk, issued: NOW + 1, sig: b.sign(handleClaimMessage("held_b2", b.pk, NOW + 1)) }); // holds held_b1
    expect(kv.m.has(`ho:${a.pk}:held_a1`)).toBe(true);
    expect(kv.ttl.get(`ho:${a.pk}:held_a1`)).toBe(60 * 86400);
    listed.length = 0;
    expect((await call(e, "DELETE", "/me", { owner: a.pk, issued: NOW + 10, sig: a.sign(eraseMessage(a.pk, NOW + 10)) })).status).toBe(200);
    expect(listed).not.toContain("hr:");
    expect(listed.every((p) => p.includes(a.pk))).toBe(true);
    expect(kv.m.has("hr:held_a1")).toBe(false);
    expect(kv.m.has(`ho:${a.pk}:held_a1`)).toBe(false);
    expect(kv.m.has("hr:held_b1")).toBe(true); // someone else's hold untouched
  });
});

